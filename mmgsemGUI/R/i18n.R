# Returns the function that looks up a text; a key without a text is returned
# as it is, so that a missing text shows up in the interface.
translator <- function() {
  function(key, ...) {
    txt <- dict[[key]]
    if (is.null(txt)) return(key)
    if (...length()) sprintf(txt, ...) else txt
  }
}
