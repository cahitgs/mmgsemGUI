pick_lang <- function(x = NULL) {
  x <- x %||% getOption("mmgsemGUI.lang", "en")
  if (length(x) == 1 && x %in% c("en", "tr")) x else "en"
}

translator <- function(lang = "en") {
  function(key, ...) {
    entry <- dict[[key]]
    if (is.null(entry)) return(key)
    txt <- unname(entry[[lang]])
    if (...length()) sprintf(txt, ...) else txt
  }
}
